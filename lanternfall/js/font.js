  function glyphFor(ch) {
    return glyphs[ch] || glyphs[ALIAS[ch]] || glyphs[ch.toUpperCase()] || glyphs['?'];
  }
  // Parse markup into runs [{text,color}]
  function parse(str, baseColor) {
    const runs = [];
    let color = baseColor;
    let buf = '';
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch === '[') {
        const j = str.indexOf(']', i);
        if (j > i) {
          const tag = str.slice(i + 1, j);
          if (tag === '' || tag[0] === '#' || NAMED[tag]) {
            if (buf) { runs.push({ text: buf, color }); buf = ''; }
            color = tag === '' ? baseColor : tag[0] === '#' ? tag : NAMED[tag];
            i = j;
            continue;
          }
        }
      }
      buf += ch;
    }
    if (buf) runs.push({ text: buf, color });
    return runs;
  }
  G.stripMarkup = (str) => parse(str, '#fff').map((r) => r.text).join('');
  G.textWidth = (str, scale) => {
    scale = scale || 1;
    const s = G.stripMarkup(String(str));
    let w = 0;
    for (let i = 0; i < s.length; i++) w += (glyphFor(s[i]).w + 1);
    return Math.max(0, w - 1) * scale;
  };
  // draw text. opts: {align:'left'|'center'|'right', shadow:color|false, scale, alpha, outline}
  G.text = (ctx, str, x, y, color, opts) => {
    opts = opts || {};
    str = String(str);
    const scale = opts.scale || 1;
    const baseColor = color || '#ffffff';
    const w = G.textWidth(str, scale);
    let cx = Math.round(opts.align === 'center' ? x - w / 2 : opts.align === 'right' ? x - w : x);
    const cy = Math.round(y);
    const runs = parse(str, baseColor);
    const prevAlpha = ctx.globalAlpha;
    if (opts.alpha !== undefined) ctx.globalAlpha = prevAlpha * opts.alpha;
    const shadow = opts.shadow === undefined ? '#000000' : opts.shadow;
    const outline = opts.outline;
    const passes = [];
    if (outline) passes.push([outline, -1, 0], [outline, 1, 0], [outline, 0, -1], [outline, 0, 1], [outline, 1, 1]);
    else if (shadow) passes.push([shadow, 1, 1]);
    passes.push([null, 0, 0]);
    for (const [pc, ox, oy] of passes) {
      let px = cx;
      for (const run of runs) {
        const a = atlasFor(pc || run.color);
        for (let i = 0; i < run.text.length; i++) {
          const g = glyphFor(run.text[i]);
          ctx.drawImage(a, g.x, 0, g.w, GH, px + ox * scale, cy + oy * scale, g.w * scale, GH * scale);
          px += (g.w + 1) * scale;
        }
      }
    }
    ctx.globalAlpha = prevAlpha;
    return w;
  };
  // word-wrap text with markup preserved. Returns lines (strings with markup).
  G.wrap = (str, maxW, scale) => {
    scale = scale || 1;
    const out = [];
    const paragraphs = String(str).split('\n');
    let carry = ''; // active color tag to carry across lines
    for (const para of paragraphs) {
      const words = para.split(' ');
      let line = '';
      for (const word of words) {
        const test = line ? line + ' ' + word : word;
        if (G.textWidth(test, scale) > maxW && line) {
          out.push(carry + line);
          carry = lastTag(carry + line);
          line = word;
        } else line = test;
      }
      out.push(carry + line);
      carry = lastTag(carry + line);
    }
    return out;
  };
  function lastTag(s) {
    let tag = '';
    const re = /\[([^\]]*)\]/g;
    let m;
    while ((m = re.exec(s))) {
      const t = m[1];
      if (t === '') tag = '';
      else if (t[0] === '#' || NAMED[t]) tag = '[' + t + ']';
    }
    return tag;
  }
  G.textBlock = (ctx, str, x, y, maxW, color, opts) => {
    opts = opts || {};
    const lines = G.wrap(str, maxW, opts.scale);
    const lh = (opts.lineH || G.LINE_H) * (opts.scale || 1);
    for (let i = 0; i < lines.length; i++) G.text(ctx, lines[i], x, y + i * lh, color, opts);
    return lines.length * lh;
  };
